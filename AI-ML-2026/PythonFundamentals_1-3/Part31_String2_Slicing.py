word = "Python"

print("First character ", word[0])    # First character
print("Last character ", word[-1])   # Last character
print("Characters from index 1 to 3 ", word[1:4])  # Characters from index 1 to 3
print("First three characters ", word[:3])   # First three characters
print("Characters from index 3 to the end ", word[3:])   # Characters from index 3 to the end