s = {1,2,2,2,3}


print(s)  # This will print {1, 2, 3} because sets do not allow duplicate elements
print(type(s))  # This will print <class 'set'>
print(len(s))  # This will print 3 because there are 3 unique elements in the set

print("# This will create & print a empty set")
empty_set = set()  # This will create an empty set
print(type(empty_set))  # This will print <class 'set'>